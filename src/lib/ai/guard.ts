import "server-only";

// Постфильтр: защита от токсичных/стереотипных формулировок.
// Сработал → регенерация со строгим промптом → фолбэк-библиотека.

const BLOCK_WORDS = [
  "вес",
  "диет",
  "похуд",
  "истерик",
  "гормон", // в уничижительном смысле (в связке ниже)
  "пмс",
  "потерпи",
  "успокойс",
  "не выдумыва",
  "всё женщины",
  "все женщины",
  "твоя девушка должна",
  "она должна",
  "не будь такой",
  "прекрати",
  "перестань",
  "физиологи", // «это физиология» — заезженное клише-оправдание
];

const BLOCK_PHRASES = [
  "это всё гормоны",
  "из-за гормонов",
  "просто потерпи",
  "успокойся",
  "всё из-за пмс",
  "не каприз", // «это не каприз, а физиология» — дословно из бан-листа промпта
  "тело просит",
  "тело в фазе",
  "просто будь рядом",
  "просто побудь рядом",
  "не ищи скрытых смыслов",
  // товарные советы «купи/принеси» — детский сад
  "купи шоколадк",
  "купить шоколадк",
  "принеси шоколадк",
  "купи цветы",
  "купить цветы",
  "купи плед",
  "купить плед",
  "купи свеч",
  "купить свеч",
  "купи вино",
  "купить вино",
  "купи конфет",
  "купить конфет",
  "купи торт",
  "купить торт",
];

export function guardViolation(text: string): boolean {
  const lower = text.toLowerCase();
  if (BLOCK_PHRASES.some((p) => lower.includes(p))) return true;
  return BLOCK_WORDS.some((w) => lower.includes(w));
}
