// Профиль партнёра → контекст для ИИ-генерации карточек.
// Три оси персонализации: тон × фокус × чтение сигналов.

export type PartnerProfile = {
  reaction: "advice" | "freeze" | "action" | "lost";
  painPoint: "unclear" | "fear" | "time" | "emotions";
  signalStyle: "direct" | "hints" | "silent" | "unknown";
  answeredAt: string; // ISO
};

const REACTION: Record<PartnerProfile["reaction"], string> = {
  advice:
    "Партнёр склонен лезть с советами. Напомни мягко: ей нужно присутствие и действие, а не решения и лекции. Формулируй совет как конкретный поступок.",
  freeze:
    "Партнёр теряется и замирает, боится сделать хуже. Дай максимально конкретный план из 1–2 простых шагов. Никакой абстракции и длинных объяснений.",
  action:
    "Партнёр из тех, кто берёт всё на себя. Похвали за инициативу и направь энергию точно в цель — что именно сегодня важнее всего.",
  lost:
    "Партнёр честно не знает, что делать. Начни с самого простого и безопасного действия, дай уверенность.",
};

const PAIN: Record<PartnerProfile["painPoint"], string> = {
  unclear:
    "Ему тяжело от непонимания, что с ней. Коротко (1 предложение) объясни фазу: это не каприз, а физиология.",
  fear:
    "Он боится сказать или сделать не то. Дай «безопасное» действие, которое точно не навредит, и фразу-пароль.",
  time:
    "У него мало времени и сил. Предложи действие на 5 минут, реальное даже в загруженный день.",
  emotions:
    "Ему самому эмоционально непросто. Добавь короткую поддержку и ему — он тоже человек. Но фокус держи на ней.",
};

const SIGNAL: Record<PartnerProfile["signalStyle"], string> = {
  direct:
    "Она просит о помощи прямо. Напомни: её просьба — не намёк, а инструкция. Делай буквально.",
  hints:
    "Она общается намёками. Помоги прочитать сигнал: что может стоять за её поведением сегодня.",
  silent:
    "Она молчит, когда ей плохо. Молчание ≠ «всё хорошо». Предложи мягкую заботу без допроса.",
  unknown:
    "Он не умеет считывать её сигналы. Дай чек-лист из 2–3 признаков, что ей сейчас нужна поддержка.",
};

export function buildPartnerContext(p: PartnerProfile | null): string {
  if (!p) {
    return "Профиль партнёра не заполнен. Давай универсальные, безопасные и конкретные советы без предположений о его стиле.";
  }
  return [REACTION[p.reaction], PAIN[p.painPoint], SIGNAL[p.signalStyle]].join(" ");
}

